<#
    collect-sms.ps1 — выгрузка СМС с Android-телефона и обезличивание в один проход.

    Зачем: корпусу нужны НАСТОЯЩИЕ сообщения. Публикации-разборы дают очищенный
    пересказ журналиста, реальное сообщение грязнее — опечатки, разговорный
    синтаксис, обрывы. Разница systematic, и она в пользу детектора.

    Приватность — не опция. Сообщения уходят в корпус только обезличенными:
    номера телефонов, карт, счетов, суммы, коды подтверждения и ссылки
    заменяются маркерами ДО того, как текст покидает этот скрипт. Исходный
    (необезличенный) файл остаётся только на диске владельца и в корпус не идёт.

    Три источника, по убыванию удобства:
      -Mode adb   — телефон по кабелю, ничего ставить не нужно (нужна отладка по USB)
      -Mode xml   — файл от приложения «SMS Backup & Restore» (если adb отказал)
      -Mode text  — простой текстовый файл, по сообщению на абзац (ручной сбор)

    Примеры:
      .\collect-sms.ps1 -Mode adb
      .\collect-sms.ps1 -Mode xml  -In "$env:USERPROFILE\Downloads\sms-20260906.xml"
      .\collect-sms.ps1 -Mode text -In .\my-sms.txt
#>

[CmdletBinding()]
param(
  [ValidateSet('adb', 'xml', 'text')]
  [string]$Mode = 'adb',
  [string]$In,
  [string]$OutDir = "$PSScriptRoot\out",
  [int]$Limit = 500,
  [string]$Adb = 'C:\ProjectS\_android-sdk\platform-tools\adb.exe'
)

$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
$stamp = Get-Date -Format 'yyyy-MM-dd'

# ─────────────────────────────────────────────────────────────
# Обезличивание. Порядок правил важен: длинные сущности снимаются
# раньше коротких, иначе номер карты распадётся на «числа».
# ─────────────────────────────────────────────────────────────
function Remove-PersonalData([string]$t) {
  if (-not $t) { return '' }
  $r = $t

  # Порядок правил: почта раньше доменов, иначе домен съедается правилом ссылки
  # и остаётся огрызок «support@<ССЫЛКА>» (замер 2026-09-06).
  $r = [regex]::Replace($r, '\b[\w\.\-]+@[\w\.\-]+\.\w{2,}\b', '<ПОЧТА>')

  # ссылки целиком. Домен маскируется единообразно намеренно: иначе детектор
  # запомнит конкретные домены корпуса вместо признака «в сообщении есть ссылка».
  $r = [regex]::Replace($r, 'https?://\S+', '<ССЫЛКА>')
  # имя домена может быть кириллическим («выплата2026.рф») — класс символов общий
  $r = [regex]::Replace($r, '\b[a-zа-яё0-9\-]+\.(ru|com|net|org|рф|info|site|online|link|top|xyz)\b\S*', '<ССЫЛКА>', 'IgnoreCase')

  # карты: 16 цифр группами, и «хвост» карты вида *1234
  $r = [regex]::Replace($r, '\b\d{4}[\s\-]?\d{4}[\s\-]?\d{4}[\s\-]?\d{4}\b', '<КАРТА>')
  $r = [regex]::Replace($r, '(\*+\s?\d{4})\b', '<КАРТА>')

  # счета и длинные номера (20 цифр — расчётный счёт)
  $r = [regex]::Replace($r, '\b\d{20}\b', '<СЧЁТ>')

  # Телефоны. Замер 2026-09-09 на реальной выгрузке: прежний шаблон требовал `+7` или
  # границу слова перед `8` и пропускал форму `79661772491` — она встречается в
  # сообщениях операторов («Абонент 79661772491 оставил Вам…»). Границы заменены на
  # проверки «не цифра» с обеих сторон.
  $r = [regex]::Replace($r, '(?<!\d)(\+?7|8)[\s\-\(]?\d{3}[\s\-\)]?\d{3}[\s\-]?\d{2}[\s\-]?\d{2}(?!\d)', '<ТЕЛЕФОН>')
  # короткие номера сервисов (0525, 900) в обороте «по номеру NNNN»
  $r = [regex]::Replace($r, '(?i)(по\s+номеру|номер)\s+\d{3,5}\b', '${1} <НОМЕР>')

  # коды подтверждения: и с подписью, и голые 4-6 цифр рядом со словом «код».
  # Окно между словом и цифрами — 25 символов: «код подтверждения: » длиннее,
  # чем кажется, и на 15 символах правило промахивалось (замер 2026-09-06).
  # Окно между словом и цифрами — 60 символов: «Код подтверждения для входа в
  # СпортРядом: 0882» даёт 34 символа, на 25 правило промахивалось (замер 2026-09-09).
  $r = [regex]::Replace($r, '(?i)(код[а-яё]*\D{0,60})\d{4,8}\b', '${1}<КОД>')
  $r = [regex]::Replace($r, '(?i)(пароль[а-яё]*\D{0,60})\d{4,8}\b', '${1}<КОД>')
  $r = [regex]::Replace($r, '(?i)\b(\d{4,6})(?=\s*[-—]\s*(код|пароль))', '<КОД>')

  # обращение по имени: «Здравствуйте, Александр!», «Уважаемый Пётр»
  $r = [regex]::Replace($r,
    '(?i)\b(здравствуйте|уважаем[а-яё]+|привет|дорог[а-яё]+|добрый день)([,\s]+)([А-ЯЁ][а-яё]{2,})\b',
    '${1}${2}<ИМЯ>')

  # Полное ФИО — встречается в уведомлениях пунктов выдачи: «Озон Афанасьев Андрей
  # Николаевич» (замер 2026-09-09, найдено контрольной выборкой уже после того, как
  # телефоны и суммы были закрыты). Признак отчества делает шаблон точным: три слова
  # с заглавной подряд без него ловили бы названия вроде «Банк Открытие Онлайн».
  $r = [regex]::Replace($r,
    '\b[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+(?:ович|евич|овна|евна|ична|инична)\b',
    '<ФИО>')
  $r = [regex]::Replace($r,
    '\b[А-ЯЁ][а-яё]+(?:ович|евич|овна|евна|ична|инична)\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+\b',
    '<ФИО>')

  # Имя с отчеством в два слова, в любом падеже: «получатель Константин Александрович»,
  # «Перевела от Игоря Николаевича». Шаблон выше требовал три слова и их пропускал.
  $r = [regex]::Replace($r,
    '\b[А-ЯЁ][а-яё]+[а-яё]?\s+[А-ЯЁ][а-яё]*(?:ович|евич|овна|евна|ич)[а-яё]*\b',
    '<ФИО>')

  # Имя с инициалом — формат уведомлений о переводе: «Пополнение … Артур Д. Доступно …».
  # Идёт ПЕРЕД правилом адреса: иначе инициал «Д.» распознаётся как «дом» и правило
  # адреса съедает инициал вместе с последующей суммой (замер 2026-09-09).
  $r = [regex]::Replace($r, '\b[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ]\.', '<ИМЯ>')

  # Адреса: с указателем типа улицы и в обороте «по адресу …».
  # `д\.` из списка убрано намеренно — оно совпадает с инициалом отчества и рвёт
  # соседние числа. «дом» осталось полным словом.
  $r = [regex]::Replace($r,
    '(?i)\b(ул\.|улица|пр-т|проспект|пер\.|переулок|бульвар|шоссе|дом)\s*[А-ЯЁа-яё\-]+,?\s*\d+[а-яё]?\b',
    '<АДРЕС>')
  $r = [regex]::Replace($r, '(?i)\bпо адресу\s+[А-ЯЁ][А-ЯЁа-яё\-]*,?\s*\d+[а-яё]?\b', 'по адресу <АДРЕС>')

  # Суммы: сохраняем ФАКТ суммы, но не величину — величина это личные данные,
  # а наличие требования денег — признак жанра, его терять нельзя.
  # Замер 2026-09-09: прежние два шаблона пропускали «50000 ₽» и «60936,88 ₽» —
  # мешала `\b` перед цифрой в связке с жадным `[\d\s]{2,}`. Один шаблон вместо двух:
  # группы разрядов через пробел или неразрывный пробел, дробная часть 1–2 знака,
  # валюта сразу за числом или через пробелы.
  # ⚠ Порядок альтернатив валюты важен: длинные раньше коротких, иначе `руб` съедает
  # начало слова «рублей» и остаётся хвост «<СУММА>лей» (замер 2026-09-09).
  $r = [regex]::Replace($r,
    '(?<![\d.,])\d{1,3}(?:[\s ]?\d{3})*(?:[.,]\d{1,2})?\s*(?:рублей|рубля|руб\.?|₽|р\.|RUB|USD|EUR|\$|€)',
    '<СУММА>', 'IgnoreCase')
  # Остаток и баланс — число после слова, без валюты рядом. `(?!\s*<)` не даёт
  # повторно захватить то, что предыдущее правило уже заменило на маркер,
  # иначе выходит «Доступно <СУММА><СУММА>» (тот же замер).
  $r = [regex]::Replace($r,
    '(?i)\b(доступно|баланс|остаток|на счету)\b[\s:]*(?!\s*<)\d[\d\s ]*(?:[.,]\d{1,2})?',
    '${1} <СУММА>')

  ($r -replace '\s+', ' ').Trim()
}

# ─────────────────────────────────────────────────────────────
# Источник 1 — телефон по кабелю
# ─────────────────────────────────────────────────────────────
function Get-FromAdb {
  if (-not (Test-Path $Adb)) { throw "adb не найден: $Adb" }

  $devices = & $Adb devices 2>&1 | Select-Object -Skip 1 | Where-Object { $_ -match '\S' }
  $online = $devices | Where-Object { $_ -match '\bdevice\b' }
  if (-not $online) {
    Write-Host 'Телефон не виден. Что проверить:' -ForegroundColor Yellow
    Write-Host '  1. Параметры разработчика включены (7 раз тапнуть «Номер сборки»).'
    Write-Host '  2. «Отладка по USB» включена.'
    Write-Host '  3. Кабель передаёт данные, а не только заряд.'
    Write-Host '  4. На экране телефона подтверждён отпечаток этого компьютера.'
    if ($devices) { Write-Host "`nadb видит: $($devices -join '; ')" }
    throw 'нет подключённого устройства'
  }
  Write-Host "устройство: $($online -join '; ')"

  $rawFile = Join-Path $OutDir "sms-raw-$stamp.txt"
  # content query — доступ от shell-пользователя; на части прошивок закрыт
  & $Adb shell content query --uri content://sms/inbox --projection date:address:body 2>&1 |
    Out-File $rawFile -Encoding utf8

  $raw = Get-Content $rawFile -Raw -Encoding UTF8
  if ($raw -match 'Permission Denial|SecurityException|Error while accessing') {
    Write-Host "`nПрошивка закрыла доступ к СМС через adb." -ForegroundColor Yellow
    Write-Host 'Запасной путь: приложение «SMS Backup & Restore» (SyncTech) → экспорт в XML → -Mode xml -In <файл>'
    throw 'adb: доступ к content://sms закрыт'
  }

  $msgs = @()
  foreach ($line in ($raw -split "`r?`n")) {
    if ($line -notmatch 'body=') { continue }
    $addr = if ($line -match 'address=([^,]*)') { $matches[1].Trim() } else { '' }
    $body = if ($line -match 'body=(.*)$')      { $matches[1].Trim() } else { '' }
    if ($body) { $msgs += [pscustomobject]@{ sender = $addr; text = $body } }
  }
  Write-Host "исходный файл (НЕ для корпуса, только для тебя): $rawFile"
  $msgs
}

# ─────────────────────────────────────────────────────────────
# Источник 2 — XML от «SMS Backup & Restore»
# ─────────────────────────────────────────────────────────────
function Get-FromXml {
  if (-not $In -or -not (Test-Path $In)) { throw "укажи -In <файл.xml>" }
  [xml]$doc = Get-Content $In -Raw -Encoding UTF8
  $doc.smses.sms |
    Where-Object { $_.type -eq '1' } |   # 1 = входящие
    ForEach-Object { [pscustomobject]@{ sender = $_.address; text = $_.body } }
}

# ─────────────────────────────────────────────────────────────
# Источник 3 — текстовый файл, сообщение = абзац
# ─────────────────────────────────────────────────────────────
function Get-FromText {
  if (-not $In -or -not (Test-Path $In)) { throw "укажи -In <файл.txt>" }
  (Get-Content $In -Raw -Encoding UTF8) -split "(\r?\n){2,}" |
    Where-Object { $_.Trim().Length -gt 10 } |
    ForEach-Object { [pscustomobject]@{ sender = ''; text = $_.Trim() } }
}

# ─────────────────────────────────────────────────────────────
$messages = switch ($Mode) {
  'adb'  { Get-FromAdb }
  'xml'  { Get-FromXml }
  'text' { Get-FromText }
}

$seen = New-Object System.Collections.Generic.HashSet[string]
$rows = @()
$i = 0
foreach ($m in $messages) {
  $clean = Remove-PersonalData $m.text
  if ($clean.Length -lt 15 -or $clean.Length -gt 600) { continue }
  $key = ($clean.ToLower() -replace '[^а-яёa-z]', '')
  if ($key.Length -lt 12 -or -not $seen.Add($key)) { continue }
  $i++
  $rows += [pscustomobject]@{
    id        = 'sms-{0:d3}' -f $i
    text      = $clean
    sender    = ($m.sender -replace '\d', '#')   # отправитель тоже маскируется
    source    = "phone/$Mode"
    genre     = 'сообщение'
    collected = $stamp
    label     = ''     # ПУСТО: метку ставит teacher-labeler, не сборщик
  }
  if ($i -ge $Limit) { break }
}

$outFile = Join-Path $OutDir "sms-anonymized-$stamp.jsonl"
$rows | ForEach-Object { $_ | ConvertTo-Json -Compress } | Out-File $outFile -Encoding utf8

Write-Host ""
Write-Host "собрано сообщений: $($rows.Count)"
Write-Host "обезличенный файл (его и присылай): $outFile"
Write-Host "SHA-256: $((Get-FileHash $outFile -Algorithm SHA256).Hash)"
Write-Host ""
Write-Host "ПРОВЕРЬ ГЛАЗАМИ перед отправкой — обезличивание работает по образцам," -ForegroundColor Yellow
Write-Host "а образцы не покрывают всё. Особенно смотри на имена и адреса." -ForegroundColor Yellow
Write-Host ""
Write-Host "--- первые 5 строк для проверки ---"
$rows | Select-Object -First 5 | ForEach-Object { "  [$($_.id)] $($_.text)" }
