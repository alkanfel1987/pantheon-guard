/**
 * test/otp-whitelist.test.js — белый класс легитимного одноразового кода.
 *
 * Тексты не выдуманы: три первых — те самые ложные срабатывания замера на не-author
 * корпусе 2026-09-09 (3 из 41 на чистой части, все одного класса). Шесть последних —
 * тексты, которые в том же замере были пойманы верно; они здесь как защита от того,
 * чтобы фильтр не задавил настоящие срабатывания.
 *
 * Граница, перенесённая из Viveka: легитимный банк ПРИСЫЛАЕТ код и просит не выдавать;
 * мошенник ЗАПРАШИВАЕТ код у жертвы. Запрос кода отменяет белый класс.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';

import { assessActionRequest, extractActions } from '../src/lexicons/actions-ru.js';
import { isLegitimateOtp, isAntifraudAdvice, checkWhitelist } from '../src/lexicons/otp-whitelist.js';

const verdictOf = (text) => assessActionRequest({ text }).verdict;

// ─── то, что давало ложные срабатывания ───

const FALSE_POSITIVES = [
  '<#> <КОД> - код для входа в VK ID. Никому не сообщайте',
  '<КОД> — код подтверждения телефона, ЮKassa (никому не говорите)',
  'Ваш код 4821, никому его не сообщайте',
];

for (const [i, text] of FALSE_POSITIVES.entries()) {
  test(`легитимный код ${i + 1} больше не поднимает вердикт`, () => {
    assert.equal(isLegitimateOtp(text), true, 'должен опознаваться как легитимный код');
    assert.equal(verdictOf(text), 'none', `вердикт должен быть none, текст: ${text}`);
  });
}

// ─── антифрод-ликбез организации ───

test('предупреждение банка о мошенниках не флагается', () => {
  const text = 'Помните: сотрудники банка никогда не просят назвать код из СМС.';
  assert.equal(isAntifraudAdvice(text), true);
  assert.equal(verdictOf(text), 'none');
});

test('предупреждение с требованием перевода поблажки НЕ получает', () => {
  const text = 'Банк никогда не просит код. Переведите деньги на безопасный счет прямо сейчас.';
  assert.equal(isAntifraudAdvice(text), false, 'требование перевода отменяет белый класс');
});

// ─── настоящий скам не должен быть подавлен ───

const TRUE_POSITIVES = [
  'продиктуйте код из СМС-сообщения',
  'На ваше имя пытаются оформить кредит, переведите деньги на безопасный счет',
  'Служба поддержки «Госуслуг». Мы зафиксировали подозрительную активность в вашем аккаунте. Для подтверждения личности отправьте код, который поступит вам в СМС',
  'из-за ошибки перевода средств, срочно подтвердите данные',
  'Никому не рассказывайте о нашем разговоре',
  'Переведите деньги, чтобы их спасти',
];

for (const [i, text] of TRUE_POSITIVES.entries()) {
  test(`настоящий приём ${i + 1} по-прежнему ловится`, () => {
    assert.equal(checkWhitelist(text).white, false, `не должен попасть в белый класс: ${text}`);
    const v = verdictOf(text);
    assert.notEqual(v, 'none', `вердикт не должен быть none, получен ${v}; текст: ${text}`);
  });
}

// ─── ключевая граница: код + секретность, но код ЗАПРАШИВАЮТ ───

test('запрос кода отменяет белый класс, даже если рядом защитная фраза', () => {
  const text = 'Ваш код подтверждения 1234. Продиктуйте код оператору, никому больше не сообщайте.';
  assert.equal(isLegitimateOtp(text), false, 'наличие запроса кода снимает поблажку');
  assert.notEqual(verdictOf(text), 'none');
});

test('текст без кода вообще белым классом не считается', () => {
  const text = 'Никому не сообщайте о нашем разговоре';
  assert.equal(isLegitimateOtp(text), false, 'нет маркера кода — нет белого класса');
});

test('extractActions по-прежнему находит действия в белом тексте (фильтр стоит выше)', () => {
  const actions = extractActions(FALSE_POSITIVES[0]);
  assert.ok(Array.isArray(actions), 'реестр действий не сломан фильтром');
});
