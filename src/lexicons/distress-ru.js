/**
 * pantheon-guard · ahimsa-veto: маркеры личного дистресса (ru)
 *
 * НАЗНАЧЕНИЕ (этическое, ahimsa): подавить флаг манипуляции, если текст —
 * самоописание эмоционального дистресса от 1-го лица («у меня нет выхода,
 * я в отчаянии»). Guard как этический фильтр НЕ должен клеймить крик о помощи
 * манипуляцией.
 *
 * ПОЧЕМУ ЛЕКСИКА, А НЕ СЕМАНТИКА (замеры 2026-06-10):
 * Различение манипуляция↔дистресс зависит от НАМЕРЕНИЯ говорящего, не формы.
 * Zero-shot NLI не берёт: самоописание отчаяния дало 0.81 по гипотезе давления
 * (выше реальной манипуляции 0.34); veto-гипотеза дистресса не разделила (−0.06).
 * Манипуляция «купите или потеряете» задевает и язык дефицита, и язык дистресса.
 * → Детерминированный лексический veto: фиксированные маркеры 1-го лица.
 *
 * ОГРАНИЧЕНИЕ (честно): эвристика, НЕ полное решение. Покрывает явные маркеры,
 * не покроет иносказательный дистресс. Ошибается в БЕЗОПАСНУЮ сторону —
 * лучше подавить флаг (пропустить возможную манипуляцию), чем обвинить
 * страдающего. Полное решение = composite (анализ лица/намерения/контекста).
 *
 * Статус: SEED ahimsa-safety эвристика.
 */

// Маркеры личного дистресса (1-е лицо + безысходность/страдание).
// Гибкие regex-паттерны по корням — естественная речь вставляет слова
// («нет ДРУГОГО выхода», «в ПОЛНОМ отчаянии»), точная подстрока их теряет.
// Нормализация входа: lowercase, ё→е.
// Паттерны без \b — в JS \b не Unicode-aware (кириллица не входит в \w).
// Фразы специфичны, частичных внутрисловных совпадений не дают.
export const DISTRESS_MARKERS = Object.freeze([
  // безысходность от 1-го лица
  { re: /(?:нет|не осталось)\s+(?:другого\s+|иного\s+)?выхода/, label: 'нет выхода' },
  { re: /выхода\s+(?:уже\s+)?нет/, label: 'выхода нет' },
  { re: /не\s+вижу\s+(?:другого\s+)?(?:выхода|смысла|вариант)/, label: 'не вижу выхода/смысла' },
  { re: /(?:все|всё|жизнь)\s+(?:потерял[оа]\s+)?(?:смысл|бессмысленн|безнадежн)/, label: 'всё бессмысленно' },
  // истощение / бессилие (1-е лицо)
  { re: /опускаются\s+руки|руки\s+опускаются/, label: 'опускаются руки' },
  { re: /сил\s+(?:больше\s+)?не\s+осталось|не\s+осталось\s+сил|нет\s+(?:больше\s+)?сил/, label: 'нет сил' },
  { re: /я\s+(?:больше\s+)?не\s+мог(?:у|ла?)/, label: 'я больше не могу' },
  { re: /я\s+(?:сломлен|на\s+пределе|выгорел|вымотан|не\s+справляюсь)/, label: 'я на пределе' },
  // страдание / страх 1-го лица
  { re: /мне\s+(?:очень\s+|так\s+)?(?:плохо|страшно|тяжело|больно|невыносимо)/, label: 'мне плохо/страшно' },
  { re: /(?:я\s+в\s+|в\s+)(?:полном\s+|глубоком\s+)?(?:отчаяни|панике|тупик|депресси)/, label: 'в отчаянии' },
  { re: /я\s+устал[ао]?\s+(?:жить|бороться|от\s+всего)/, label: 'я устал жить/бороться' },
  // одиночество / безнадёжность
  { re: /меня\s+никто\s+не\s+понимает|я\s+никому\s+не\s+нужен/, label: 'одиночество' },
  { re: /надежд[ыа]\s+(?:не\s+осталось|нет|больше\s+нет)/, label: 'надежды нет' },
]);

function norm(s) {
  return s.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
}

/**
 * Возвращает метки найденных маркеров дистресса (или []). Непустой результат =
 * сигнал ahimsa-veto: вызывающий слой ДОЛЖЕН подавить флаг манипуляции.
 * @param {string} text
 * @returns {string[]}
 */
export function distressMarkers(text) {
  if (typeof text !== 'string' || !text) return [];
  const n = norm(text);
  return DISTRESS_MARKERS.filter((m) => m.re.test(n)).map((m) => m.label);
}

/** @returns {boolean} true если текст несёт хотя бы один маркер дистресса. */
export function hasDistress(text) {
  return distressMarkers(text).length > 0;
}
