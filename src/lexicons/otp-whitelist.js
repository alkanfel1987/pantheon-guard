/**
 * Белые классы: легитимный одноразовый код и антифрод-предупреждение.
 *
 * ПЕРЕНОС ИЗ VIVEKA (`C:/ProjectS/viveka-android/app/src/main/java/com/pantheon/viveka/
 * GuardEngine.kt`, разделы «ЛЕГИТИМНЫЙ OTP» и «АНТИМОШЕННИЧЕСКОЕ ПРЕДУПРЕЖДЕНИЕ»).
 * Логика и границы сохранены дословно, изменён только язык.
 *
 * ЗАЧЕМ. Замер на не-author корпусе 2026-09-09 дал 3 ложных срабатывания из 41, и все три —
 * один класс: легитимный код подтверждения.
 *
 *   «<КОД> — код для входа в VK ID. Никому не сообщайте»
 *   «<КОД> — код подтверждения телефона, ЮKassa (никому не говорите)»
 *   «Для подписания договора введите код <КОД>»
 *
 * Слой действий видит «никому не сообщайте» и помечает класс `isolate` — требование
 * секретности. Но мошенник просит молчать, чтобы жертва не проверила, а банк — чтобы
 * жертву защитить. Формы совпадают, смысл обратный.
 *
 * ГРАНИЦА, на которой всё держится (формулировка Viveka):
 *   легитимный банк **присылает** код и просит его не выдавать — это защита;
 *   мошенник **запрашивает** код у жертвы — это приём.
 * Поэтому наличие запроса кода (solicit) отменяет обе поблажки: подавлять секретность
 * при живом запросе кода нельзя.
 */

/** Признаки того, что в тексте есть сам одноразовый код. */
export const OTP_CODE_MARKERS = Object.freeze([
  /(одноразов|ваш|проверочн|секретн)[а-яё]*\s+код/i,
  /код[а-яё]*\s+(подтвержд|для\s+входа|авториз|операци|транзакц|доступа)/i,
  /код:?\s*\d{3,8}/i,
  /verification code|one-time (code|password)|\botp\b|login code|security code/i,
]);

/**
 * Защитная инструкция «не сообщайте код» — легитимная, банк защищает клиента.
 * Английские формы широкие намеренно: они гейтятся наличием кода, поэтому безопасны.
 */
export const OTP_PROTECT_PHRASES = Object.freeze([
  /никому\s+(его|это|их|код[а-яё]*)?\s*не\s+сообщ/i,
  /не\s+сообщ[а-яё]+\s+(его\s+|код[а-яё]*\s+)?никому/i,
  /не\s+передавайте\s+(этот\s+)?код|не\s+называйте\s+(этот\s+)?код/i,
  // ⚠ Ниже — РАСШИРЕНИЕ переноса, не дословная копия Viveka. Её шаблоны знают
  // «не сообщайте», «не передавайте», «не называйте», но не знают «не говорите» —
  // а именно так пишет ЮKassa: «код подтверждения телефона (никому не говорите)».
  // Пробел вскрылся на реальном сообщении с устройства 2026-09-09, в синтетике его
  // не было. Форма «не разглашайте» добавлена по тому же основанию — она встречается
  // у операторов связи.
  /никому\s+(его|это|их|код[а-яё]*)?\s*не\s+(говор|разглаш|раскрыв)/i,
  /не\s+(говорите|разглашайте|раскрывайте)\s+(его\s+|код[а-яё]*\s+)?никому/i,
  /(do\s+not|don.?t)\s+(share|disclose|give|reveal|tell)\b/i,
  /keep\s+(it|this|the\s+code|your\s+code)\s+(secret|safe|private|to\s+yourself)/i,
]);

/** Запрос кода У пользователя — это уже приём, а не защита. Отменяет белый класс. */
export const OTP_SOLICIT = Object.freeze([
  /продиктуй|назови(те)?\s+(нам\s+)?код|сообщи(те)?\s+(нам\s+)?код|скажи(те)?\s+(нам\s+)?код|введите\s+код\s+здесь/i,
  /(give|tell|send|share)\s+(me|us)\b.{0,30}(code|otp)/i,
]);

/** Банк или госорган сам предупреждает о мошенничестве — это ликбез, не приём. */
export const ANTIFRAUD_ADVICE = Object.freeze([
  /банк[а-яё]*\s+(никогда\s+)?не\s+(просит|просят|запрашива|звон)/i,
  /никогда\s+не\s+(сообщайте|называйте|говорите)\s+(свой\s+|никому\s+)?(код|пароль|пин|cvv|данные)/i,
  /остерегайтесь\s+мошенник|будьте\s+бдительн|не\s+поддавайтесь\s+на/i,
  /это\s+(могут\s+быть\s+|признак[аи]?\s+)?мошенник/i,
  /(настоящие|официальные)\s+(сотрудники|представители)[^.]{0,60}(никогда\s+)?не\s+(прос|требу|звон)/i,
  /(bank|we)\s+(will\s+)?never\s+(ask|call|request)/i,
]);

/** Требование перевода — отменяет поблажку антифрод-совету (Viveka: TRANSFER_PATTERNS). */
const TRANSFER_DEMAND = Object.freeze([
  /перевед[иет][а-яё]*\s+(деньги|средства|сумму)/i,
  /(безопасн|резервн|специальн)[а-яё]*\s+счет|счёт/i,
  /(transfer|send|wire)\s+(the\s+)?(money|funds)/i,
]);

const any = (patterns, text) => patterns.some((re) => re.test(text));

/**
 * Легитимный одноразовый код: код есть, защитная фраза есть, запроса кода нет.
 * @param {string} text
 * @returns {boolean}
 */
export function isLegitimateOtp(text) {
  if (!text) return false;
  const hasCode = any(OTP_CODE_MARKERS, text);
  const hasProtect = any(OTP_PROTECT_PHRASES, text);
  const solicits = any(OTP_SOLICIT, text);
  return hasCode && hasProtect && !solicits;
}

/**
 * Антифрод-предупреждение: совет есть, запроса кода нет, требования перевода нет.
 * Без последних двух условий сам ликбез банка читался бы как мошенничество.
 * @param {string} text
 * @returns {boolean}
 */
export function isAntifraudAdvice(text) {
  if (!text) return false;
  const advice = any(ANTIFRAUD_ADVICE, text);
  const solicits = any(OTP_SOLICIT, text);
  const demandsTransfer = any(TRANSFER_DEMAND, text);
  return advice && !solicits && !demandsTransfer;
}

/**
 * Общая проверка белого класса — то, что вызывает слой действий.
 * @param {string} text
 * @returns {{white: boolean, kind: 'legitimate-otp'|'antifraud-advice'|null}}
 */
export function checkWhitelist(text) {
  if (isLegitimateOtp(text)) return { white: true, kind: 'legitimate-otp' };
  if (isAntifraudAdvice(text)) return { white: true, kind: 'antifraud-advice' };
  return { white: false, kind: null };
}
