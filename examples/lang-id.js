/**
 * Индикатор языка для опорного перевода: письменность решает первой, частоты — потом.
 *
 * Замер 2026-09-16 (vault …/Прогоны/2026-09-16-опорный-язык-ПРЕРЕГ.md, `lang-id-probe.js`),
 * 5 языков × 200 текстов, доля кусков с верным языком:
 *   по куску `franc` 90,3 % (русский 72 %) · по всему тексту 93,5 % (русский 82 %) ·
 *   буквы + текст 96,8 % · **письменность + текст 98,7 %** (ru 96 · de 99 · zh 100 · ar 99 · kk 100).
 *
 * Почему так: `franc` считает трёхбуквенные сочетания и на кириллице путает русский с болгарским
 * даже на целом тексте; куски из адресов и кода он относил к французскому и каталанскому.
 * Письменность эти два класса ошибок снимает без модели.
 *
 * ponytail: приметы заданы для письменностей и кириллических языков, которые нам встречаются;
 * всё прочее уходит в franc по целому тексту.
 */
import { franc } from 'franc';

const SCRIPTS = [
  ['cmn', /[一-鿿㐀-䶿]/],   // ханьцзы
  ['jpn', /[぀-ヿ]/],                // кана
  ['kor', /[가-힯]/],                // хангыль
  ['arb', /[؀-ۿ]/],                // арабская вязь
  ['ell', /[Ͱ-Ͽ]/],
  ['heb', /[֐-׿]/],
];
const CYRILLIC = [
  ['kaz', /[әғқңөұүһі]/i],   // казахские буквы, которых нет в русском
  ['ukr', /[їієґ]/i],
  ['bel', /[ўі]/i],
  ['rus', /[ыэъё]/i],        // болгарский обходится без ы и э — они и решают
];

/** Язык куска по письменности; null — письменность не различает (латиница, голая кириллица). */
export function byWriting(text) {
  for (const [code, re] of SCRIPTS) if (re.test(text)) return code;
  if (/[Ѐ-ӿ]/.test(text)) {
    for (const [code, re] of CYRILLIC) if (re.test(text)) return code;
  }
  return null;
}

/**
 * @param {string} chunk кусок текста
 * @param {string} whole язык всего текста (`franc` по нему считается один раз)
 * @returns {string} трёхбуквенный код языка
 */
export function detectLang(chunk, whole) {
  return byWriting(chunk) || whole;
}

export { franc };
